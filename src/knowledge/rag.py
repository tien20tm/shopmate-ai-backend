
import re
from functools import lru_cache

from langchain_core.output_parsers import StrOutputParser
from langchain_openai import ChatOpenAI

from src.config import settings
from src.chat.prompts import RAG_PROMPT
from src.knowledge.retriever import search_knowledge


FALLBACK_ANSWER = (
    "Mình chưa tìm thấy thông tin này trong "
    "chính sách hiện có của ShopMate."
)


@lru_cache
def get_rag_chain():
    llm = ChatOpenAI(
        model=settings.OPENAI_CHAT_MODEL,
        temperature=0,
        timeout=30,
        max_retries=2,
        api_key=settings.OPENAI_API_KEY,
    )

    return RAG_PROMPT | llm | StrOutputParser()


async def answer_from_knowledge(
    question: str,
    top_k: int = 4,
) -> dict:
    # Step 1: Retrieve relevant documents
    documents = await search_knowledge(
        query=question,
        top_k=top_k,
    )

    if not documents:
        return {
            "answer": FALLBACK_ANSWER,
            "sources": [],
        }

    # Step 2: Build context with reference numbers
    context_parts = []

    for index, doc in enumerate(documents, start=1):
        context_parts.append(
            f"[{index}]\n"
            f"Title: {doc['title']}\n"
            f"Document ID: {doc['document_id']}\n"
            f"Content:\n{doc['content']}"
        )

    context = "\n\n---\n\n".join(context_parts)

    # Step 3: Generate answer using retrieved context
    chain = get_rag_chain()

    answer = await chain.ainvoke({
        "question": question,
        "context": context,
    })

    # Step 4: Extract citation numbers from answer
    cited_numbers = {
        int(number)
        for number in re.findall(r"\[(\d+)\]", answer)
    }

    # Source metadata is taken from database results,
    # not generated by the LLM.
    sources = [
        {
            "ref": f"[{index}]",
            "document_id": doc["document_id"],
            "title": doc["title"],
            "chunk_index": doc["chunk_index"],
            "similarity": doc["similarity"],
        }
        for index, doc in enumerate(documents, start=1)
        if index in cited_numbers
    ]

    return {
        "answer": answer,
        "sources": sources,
    }
